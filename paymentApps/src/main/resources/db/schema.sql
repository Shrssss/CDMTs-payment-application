CREATE TABLE ITEM_TABLE (
    ITEMID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ITEM_NAME VARCHAR(255) NOT NULL,
    PRICE INT NOT NULL,
    IMAGE_PATH VARCHAR(1024) DEFAULT NULL,
    AVAILABLE BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE ORDER_TABLE (
    ORDERID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ORDER_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RESERVED_TIME DATETIME,
    SERVING_STATUS TINYINT NOT NULL DEFAULT 0,
    PAYMENTID VARCHAR(255),
    PAYMENT_STATUS BOOLEAN NOT NULL DEFAULT FALSE,
    IDEMPOTENCY_KEY VARCHAR(255) UNIQUE
);

CREATE TABLE ORDER_ITEM_TABLE (
    ORDER_ITEM_ID BIGINT AUTO_INCREMENT PRIMARY KEY,
    ORDERID BIGINT NOT NULL,
    ITEMID BIGINT NOT NULL,
    QUANTITY INT NOT NULL,

    CONSTRAINT FK_ORDER_ITEM_ORDER
        FOREIGN KEY (ORDERID)
        REFERENCES ORDER_TABLE (ORDERID),

    CONSTRAINT FK_ORDER_ITEM_ITEM
        FOREIGN KEY (ITEMID)
        REFERENCES ITEM_TABLE (ITEMID),

    CONSTRAINT CHK_ORDER_ITEM_QUANTITY
        CHECK (QUANTITY > 0)
);